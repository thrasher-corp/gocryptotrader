// benchmarkResultPattern matches a measurement as go test prints one, a number then its unit, or as
// benchstat does, a value ± its spread set apart by two or more spaces. Prose naming a unit or a
// tolerance does not match.
var benchmarkResultPattern = regexp.MustCompile(
	`\d\s*(?:[nuµm]?s/op|B/op|allocs/op|[KMGT]?B/s)` +
		`|(?:^|\s\s|\t)[-+]?\d\S*\s*±\s*-?(?:\d+(?:\.\d+)?%|∞|\?)(?:\s+[\d~+\-?¹²³⁴⁵⁶⁷⁸⁹]|\s*(?:\*/\s*)?$)`)

// templateAction matches a text/template action, which can span lines
var templateAction = regexp.MustCompile(`(?s)\{\{.*?\}\}`)

// goTemplate reports whether src is a template of Go source: once its actions are removed, its first
// token outside comments is the package clause
func goTemplate(src []byte) bool {
	src = templateAction.ReplaceAll(src, nil)
	var s scanner.Scanner
	s.Init(token.NewFileSet().AddFile("", -1, len(src)), src, func(token.Position, string) {}, 0)
	_, tok, _ := s.Scan()
	return tok == token.PACKAGE
}

// commentedResults returns a "file:line: text" description of each comment line in src holding a
// benchmark result
func commentedResults(path string, src []byte) []string {
	var found []string
	fset := token.NewFileSet()
	var s scanner.Scanner
	// A file that does not compile still has comments to check, and the build reports its error
	s.Init(fset.AddFile(path, -1, len(src)), src, func(token.Position, string) {}, scanner.ScanComments)
	for {
		pos, tok, lit := s.Scan()
		if tok == token.EOF {
			return found
		}
		if tok != token.COMMENT {
			continue
		}
		start := fset.Position(pos).Line
		for i, line := range strings.Split(lit, "\n") {
			if benchmarkResultPattern.MatchString(line) {
				found = append(found, fmt.Sprintf("%s:%d: %s", path, start+i, strings.TrimSpace(line)))
			}
		}
	}
}

func TestCommentedResults(t *testing.T) {
	t.Parallel()
	src := "package x\n" +
		"\n" +
		"// 13636467	        84.26 ns/op	     141 B/op	       1 allocs/op\n" + // line 3
		"func BenchmarkA() {}\n" +
		"\n" +
		"/*\n" +
		"Before: 18.58 µs/op  3120 B/op  65 allocs/op\n" + // line 7, unstarred in a block comment
		"*/\n" +
		"var url = \"https://example.invalid/5 ns/op\"\n" + // a string literal, not a comment
		"var m = metrics[\"ns/op\"] // reads the ns/op metric\n" + // prose naming units
		"// Throughput reached 120 MB/s\n" + // line 11
		"var y = 2 // keeps this at 0 allocs/op\n" + // line 12, trailing comment
		"//         │   sec/op    │   sec/op     vs base              │\n" + // a benchstat header names units without a number
		"// Alive-4    14.21n ± 4%   14.41n ± 6%       ~ (p=0.905 n=6)\n" + // line 14, a benchstat row
		"// Alive-4       14.06n ± ∞ ¹   14.89n ± ∞ ¹       ~ (p=1.000 n=1) ²\n" + // line 15, one from too few samples
		"// ZeroAlloc-4   0.000 ± ?   0.000 ± ?  ~ (p=1.000 n=10)\n" + // line 16, one whose spread could not be computed
		"/* fast path   10.25n ± 2% */\n" + // line 17, a projected row in a one-line block comment
		"// Allow 100 ± 5% clock drift before rejecting a sample\n" + // a tolerance in prose, not a result
		"// Prices are accepted within 100 ± 5%\n" + // nor is one ending a sentence
		"// Signed-4   -100.0n ± 1%\n" // line 20, a row of a negative custom metric
	exp := []string{
		"x.go:3: // 13636467	        84.26 ns/op	     141 B/op	       1 allocs/op",
		"x.go:7: Before: 18.58 µs/op  3120 B/op  65 allocs/op",
		"x.go:11: // Throughput reached 120 MB/s",
		"x.go:12: // keeps this at 0 allocs/op",
		"x.go:14: // Alive-4    14.21n ± 4%   14.41n ± 6%       ~ (p=0.905 n=6)",
		"x.go:15: // Alive-4       14.06n ± ∞ ¹   14.89n ± ∞ ¹       ~ (p=1.000 n=1) ²",
		"x.go:16: // ZeroAlloc-4   0.000 ± ?   0.000 ± ?  ~ (p=1.000 n=10)",
		"x.go:17: /* fast path   10.25n ± 2% */",
		"x.go:20: // Signed-4   -100.0n ± 1%",
	}
	assert.Equal(t, exp, commentedResults("x.go", []byte(src)),
		"every comment line holding a measurement should be found, and nothing outside comments")
}

func TestGoTemplate(t *testing.T) {
	t.Parallel()
	goSource := "{{define \"test\"}}\npackage {{.Name}}\n\n// 13636467\t        84.26 ns/op\t     141 B/op\t       1 allocs/op\nfunc {{.Name}}() {}\n{{end}}\n"
	for _, tc := range []struct {
		name, src string
		exp       bool
	}{
		{"a Go source template", goSource, true},
		{"one opening with a comment and an action", "// Code generated by a template\n{{template \"header\" .}}\npackage x\n", true},
		{"one opening with a multi-line action", "{{/*\nlicence\n*/}}\npackage x\n", true},
		{"a Markdown template with a Go example", "{{define \"readme\"}}\n# {{.Name}}\n\n```go\npackage main\n// 1 allocs/op\n```\n{{end}}\n", false},
		{"an HTML template", "{{define \"report\"}}\n<!doctype html>\n{{end}}\n", false},
		{"a text template", "single-channel\n{{range .}}{{.}}\n{{end}}\n", false},
		{"an empty template", "", false},
	} {
		assert.Equalf(t, tc.exp, goTemplate([]byte(tc.src)), "goTemplate should judge %s", tc.name)
	}
	assert.Equal(t, []string{"x.tmpl:4: // 13636467\t        84.26 ns/op\t     141 B/op\t       1 allocs/op"},
		commentedResults("x.tmpl", []byte(goSource)), "a result in a Go template's comment should be found")
}

// gitCommand runs git in dir without the GIT_ variables a git hook exports, which would point it at the
// hook's repository
func gitCommand(t *testing.T, dir string, args ...string) *exec.Cmd {
	t.Helper()
	cmd := exec.CommandContext(t.Context(), "git", args...)
	cmd.Dir = dir
	cmd.Env = slices.DeleteFunc(os.Environ(), func(kv string) bool { return strings.HasPrefix(kv, "GIT_") })
	return cmd
}

func TestGitCommandIgnoresHookEnvironment(t *testing.T) {
	// No t.Parallel, since t.Setenv changes the process's environment
	hook := t.TempDir()
	require.NoError(t, gitCommand(t, hook, "init", "-q").Run(), "git init must not error for the hook's repository")
	t.Setenv("GIT_DIR", filepath.Join(hook, ".git"))
	t.Setenv("GIT_INDEX_FILE", filepath.Join(hook, ".git", "index"))
	t.Setenv("GIT_WORK_TREE", hook)

	dir := t.TempDir()
	writeFiles(t, dir, map[string]string{"a.go": "package a\n"})
	for _, args := range [][]string{{"init", "-q"}, {"add", "a.go"}} {
		require.NoErrorf(t, gitCommand(t, dir, args...).Run(), "git %s must not error", args[0])
	}
	for _, tc := range []struct {
		dir  string
		args []string
		exp  string
	}{
		{dir, []string{"ls-files"}, "a.go\n"},
		{hook, []string{"ls-files"}, ""},
		{hook, []string{"config", "core.bare"}, "false\n"},
	} {
		out, err := gitCommand(t, tc.dir, tc.args...).Output()
		require.NoErrorf(t, err, "git %s must not error", tc.args[0])
		assert.Equalf(t, tc.exp, string(out), "git %s in %s should show that only the new repository changed", tc.args[0], tc.dir)
	}
}

// checkedSource is a Go source or Go template the comment check reads, with its path relative to the
// repository root
type checkedSource struct {
	rel string
	src []byte
}

// checkedSources returns the Go sources and Go templates under root, from its git index, or by walking
// a tree exported without one
func checkedSources(t *testing.T, root string) []checkedSource {
	t.Helper()
	var paths []string
	if _, err := os.Stat(filepath.Join(root, ".git")); err == nil {
		// The index leaves out untracked and vendored files
		out, err := gitCommand(t, root, "-c", "safe.directory=*", "ls-files", "-z", "*.go", "*.tmpl").Output()
		require.NoError(t, err, "tracked Go sources and templates must be listed")
		for path := range strings.SplitSeq(string(out), "\x00") {
			if path != "" {
				paths = append(paths, filepath.Join(root, filepath.FromSlash(path)))
			}
		}
	} else {
		// An exported tree has no index, as in the Docker job
		require.NoError(t, filepath.WalkDir(root, func(path string, d fs.DirEntry, err error) error {
			// cmd/exchange_template's test can remove a directory it created mid-walk
			if errors.Is(err, fs.ErrNotExist) {
				return nil
			}
			if err != nil {
				return err
			}
			if d.IsDir() && path != root && (d.Name() == ".git" || d.Name() == "vendor") {
				return fs.SkipDir
			}
			if ext := filepath.Ext(path); !d.IsDir() && (ext == ".go" || ext == ".tmpl") {
				paths = append(paths, path)
			}
			return nil
		}), "the repository's Go sources must be walked")
	}
	var sources []checkedSource
	for _, path := range paths {
		src, err := os.ReadFile(path)
		if errors.Is(err, fs.ErrNotExist) {
			continue // Deleted but still in the index
		}
		require.NoErrorf(t, err, "reading %s must not error", path)
		if filepath.Ext(path) == ".tmpl" && !goTemplate(src) {
			continue
		}
		rel, err := filepath.Rel(root, path)
		require.NoErrorf(t, err, "%s must be inside the repository", path)
		sources = append(sources, checkedSource{rel: filepath.ToSlash(rel), src: src})
	}
	return sources
}

func TestCheckedSources(t *testing.T) {
	t.Parallel()
	files := map[string]string{
		"a/a.go":        "package a\n",
		"a/gen.tmpl":    "{{define \"gen\"}}\npackage {{.Name}}\n{{end}}\n",
		"a/readme.tmpl": "{{define \"readme\"}}\n# A\n{{end}}\n",
		"a/notes.md":    "// 1 allocs/op\n",
	}
	exported := t.TempDir()
	writeFiles(t, exported, files)
	writeFiles(t, exported, map[string]string{"vendor/v/v.go": "package v\n", "sub/.git/x.go": "package x\n"})
	tracked := t.TempDir()
	writeFiles(t, tracked, files)
	writeFiles(t, tracked, map[string]string{"untracked.go": "package untracked\n", "a/deleted.go": "package a\n"})
	for _, args := range [][]string{{"init", "-q"}, {"add", "a"}} {
		require.NoErrorf(t, gitCommand(t, tracked, args...).Run(), "git %s must not error", args[0])
	}
	require.NoError(t, os.Remove(filepath.Join(tracked, "a", "deleted.go")), "removing a tracked file must not error")
	for _, tc := range []struct {
		root string
		exp  []string
	}{
		{exported, []string{"a/a.go", "a/gen.tmpl"}},
		{tracked, []string{"a/a.go", "a/gen.tmpl"}},
	} {
		sources := checkedSources(t, tc.root)
		got := make([]string, 0, len(sources))
		for _, s := range sources {
			got = append(got, s.rel)
		}
		assert.Equalf(t, tc.exp, got, "checkedSources should list the Go sources and Go templates under %s", tc.root)
	}
}

// TestNoBenchmarkResultsInComments keeps benchmark results out of comments, where nothing checks them.
// misc_checks.sh runs it by name.
func TestNoBenchmarkResultsInComments(t *testing.T) {
	t.Parallel()
	root, err := filepath.Abs(filepath.Join("..", ".."))
	require.NoError(t, err, "the repository root must resolve")
	sources := checkedSources(t, root)
	require.NotEmpty(t, sources, "the repository must contain Go sources")
	for _, s := range sources {
		assert.Emptyf(t, commentedResults(s.rel, s.src),
			"%s should hold no benchmark results in comments; allocation budgets belong in benchmarks/baseline.json", s.rel)
	}
}
